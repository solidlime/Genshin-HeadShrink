def _gf256_mul(a: int, b: int) -> int:
    if a == 0 or b == 0:
        return 0
    return GF256_EXP[(GF256_LOG[a] + GF256_LOG[b]) % 0xFF]


def _aes_expand(key: bytes) -> bytearray:
    """Modified AES key expansion (Blb3 variant)."""
    assert len(key) == 16
    keys = bytearray(176)
    # Initial: keys[i] = key[Blb3AESShift[i]]
    for i in range(16):
        keys[i] = key[BLB3_AES_SHIFT[i]]
    offset = 0x1f
    for rnd in range(10):
        a = BLB3_AES_SBOX[keys[offset - 0x14]]
        b = BLB3_AES_SBOX[keys[offset - 0x10]]
        c = (BLB3_AES_SBOX[keys[offset - 0x18]] ^ keys[offset - 0x18] ^ POWER_SCHEDULE[rnd] ^ keys[offset - 0x1f]) & 0xff
        d = BLB3_AES_SBOX[keys[offset - 0x1c]]
        temp = 0
        keys[offset - 0xf] = c
        temp = (a ^ keys[offset - 0x14] ^ keys[offset - 0x1b]) & 0xff
        keys[offset - 0xb] = temp
        a = (b ^ keys[offset - 0x10] ^ keys[offset - 0x17]) & 0xff
        keys[offset - 7] = a
        b = (d ^ keys[offset - 0x1c] ^ keys[offset - 0x13]) & 0xff
        keys[offset - 3] = b
        c = (c ^ keys[offset - 0x1e]) & 0xff
        keys[offset - 0xe] = c
        temp = (temp ^ keys[offset - 0x1a]) & 0xff
        keys[offset - 10] = temp
        a = (a ^ keys[offset - 0x16]) & 0xff
        keys[offset - 6] = a
        b = (b ^ keys[offset - 0x12]) & 0xff
        keys[offset - 2] = b
        c = (c ^ keys[offset - 0x1d]) & 0xff
        keys[offset - 0xd] = c
        temp = (temp ^ keys[offset - 0x19]) & 0xff
        keys[offset - 9] = temp
        a = (a ^ keys[offset - 0x15]) & 0xff
        keys[offset - 5] = a
        b = (b ^ keys[offset - 0x11]) & 0xff
        keys[offset - 1] = b
        keys[offset - 0xc] = (c ^ keys[offset - 0x1c]) & 0xff
        keys[offset - 8] = (temp ^ keys[offset - 0x18]) & 0xff
        keys[offset - 4] = (a ^ keys[offset - 0x14]) & 0xff
        keys[offset] = (b ^ keys[offset - 0x10]) & 0xff
        offset += 0x10
    return keys


def _sub_bytes(a: bytearray) -> None:
    for i in range(len(a)):
        a[i] ^= BLB3_AES_SBOX[a[i]]


def _xor_round_key(state: bytearray, keys: bytearray, rnd: int) -> None:
    for i in range(4):
        for j in range(4):
            state[i * 4 + j] ^= keys[i + j * 4 + rnd * 16]


def _shift_rows(state: bytearray) -> None:
    temp = bytearray(state)
    for i in range(16):
        state[i] = temp[SHIFT_ROWS_TABLE[i]]


def _mix_col(state: bytearray, off: int) -> None:
    a0, a1, a2, a3 = state[off], state[off+1], state[off+2], state[off+3]
    state[off]   = LOOKUP_G2[a0] ^ LOOKUP_G3[a1] ^ a2 ^ a3
    state[off+1] = LOOKUP_G2[a1] ^ LOOKUP_G3[a2] ^ a3 ^ a0
    state[off+2] = LOOKUP_G2[a2] ^ LOOKUP_G3[a3] ^ a0 ^ a1
    state[off+3] = LOOKUP_G2[a3] ^ LOOKUP_G3[a0] ^ a1 ^ a2


def _mix_cols(state: bytearray) -> None:
    for off in (0, 4, 8, 12):
        _mix_col(state, off)


def aes_encrypt(m: bytes, k: bytes) -> bytearray:
    """Modified AES-128 encrypt (Blb3 variant, XOR-based SubBytes)."""
    keys = _aes_expand(k)
    c = bytearray(m[:16])
    _xor_round_key(c, keys, 0)
    for i in range(9):
        _sub_bytes(c)
        _shift_rows(c)
        _mix_cols(c)
        _xor_round_key(c, keys, i + 1)
    _sub_bytes(c)
    _shift_rows(c)
    _xor_round_key(c, keys, 10)
    return c


def descramble(buf: bytearray) -> None:
    """GF256-based descramble (3 rounds)."""
    n = len(buf)
    vector = bytearray(n)
    for i in range(3):
        for j in range(n):
            k = BLB3_SHIFT_ROW[(2 - i) * 0x10 + j]
            idx = j % 8
            vector[j] = BLB3_KEY[idx] ^ BLB3_SBOX[(j % 4 * 0x100) | _gf256_mul(BLB3_MUL[idx], buf[k % n])]
        buf[:] = vector


def rc4(buf: bytearray) -> None:
    """Custom RC4 variant used in Blb3 (uses first 16 bytes as key-schedule seed)."""
    S = bytearray(BLB3_RC4_KEY)
    T = bytearray(256)
    for i in range(0, 256, 2):
        T[i] = buf[i & 6]
        T[i + 1] = buf[(i + 1) & 7]
    j = 0
    for i in range(256):
        j = (j + S[i] + T[i]) % 256
        S[i], S[j] = S[j], S[i]
    i = j = 0
    for it in range(len(buf) - 0x10):
        i = (i + 1) % 256
        j = (j + S[i]) % 256
        S[i], S[j] = S[j], S[i]
        K = S[(S[j] + S[i]) % 256]
        mode = buf[(i % 8) + 8] % 3
        idx = it + 0x10
        if mode == 0:
            buf[idx] ^= K
        elif mode == 1:
            buf[idx] = (buf[idx] - K) & 0xff
        else:
            buf[idx] = (buf[idx] + K) & 0xff


def decrypt(header: bytes, buffer: bytearray) -> None:
    """Main Blb3 Decrypt: applied to first 128 bytes of buffer.
    Modifies buffer in-place.
    """
    assert len(header) == 16
    n = min(128, len(buffer))
    # Step 1: XOR first 16 bytes with header (mutate buffer directly)
    for i in range(min(n, 16)):
        buffer[i] ^= header[i]
    if n >= 16:
        # Step 2: modified AES encrypt first 16 bytes with header as key
        new_first = aes_encrypt(bytes(buffer[:16]), header)
        buffer[:16] = new_first
        # Step 3: custom RC4 on bytes > 16 (uses first 16 as seed)
        # rc4() expects a bytearray and mutates in-place via buf[k] = ...
        # So pass a copy of first n bytes and copy back
        if n > 16:
            tmp = bytearray(buffer[:n])
            rc4(tmp)
            buffer[:n] = tmp
        # Step 4: GF256 descramble first 16 bytes (3 rounds)
        tmp = bytearray(buffer[:16])
        descramble(tmp)
        buffer[:16] = tmp
